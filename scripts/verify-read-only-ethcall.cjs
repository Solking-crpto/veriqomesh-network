/**
 * Read-Only eth_call Verification of agreeTransaction
 * Uses the updated SDK Client to encode the call and simulates execution on Monad Testnet RPC.
 */
const { ethers } = require('ethers');
const { TrustMeshClient } = require('../packages/sdk/dist/index.js');

const RPC_URL = 'https://testnet-rpc.monad.xyz';
const CHAIN_ID = 10143;
const ESCROW_ADDRESS = '0x925ea880cA53DE0352b84B24d0C0dee5B258015A';
const SELLER_ADDRESS = '0x0e73dBFf9047423b520FA9fc23a95645fC986Ee8';
const TARGET_TX_ID = '0xbbd0176291d62b32c3e096d0314c0fab6bcfa9131c1b26a825b3ce994e645f5e';

async function main() {
  const provider = new ethers.JsonRpcProvider(RPC_URL, CHAIN_ID);
  const client = new TrustMeshClient({
    escrowContractAddress: ESCROW_ADDRESS,
    rpcUrl: RPC_URL,
    readProvider: provider,
  });

  console.log('========================================================================');
  console.log('   READ-ONLY eth_call SIMULATION FOR agreeTransaction(txId)');
  console.log('========================================================================\n');

  // Verify selector generated by the updated SDK
  const selector = client.getSelector('agreeTransaction(bytes32)');
  console.log(`1. SDK Selector for agreeTransaction(bytes32): ${selector}`);
  if (selector !== '0xbedf318b') {
    console.error(`❌ Expected selector 0xbedf318b, got ${selector}`);
    process.exit(1);
  }
  console.log('   ✓ Matches canonical deployed selector 0xbedf318b\n');

  // Verify encoded calldata from SDK
  const calldata = client._encodeSingleIdCall('agreeTransaction(bytes32)', TARGET_TX_ID);
  console.log(`2. SDK Calldata generated:`);
  console.log(`   ${calldata}`);
  const expectedCalldata = '0xbedf318bbbd0176291d62b32c3e096d0314c0fab6bcfa9131c1b26a825b3ce994e645f5e';
  if (calldata.toLowerCase() !== expectedCalldata.toLowerCase()) {
    console.error(`❌ Calldata mismatch: expected ${expectedCalldata}`);
    process.exit(1);
  }
  console.log('   ✓ Calldata matches expected bytes exactly\n');

  // Perform read-only eth_call directly against Monad Testnet RPC
  console.log(`3. Executing read-only eth_call against Monad Testnet RPC...`);
  console.log(`   Target Contract : ${ESCROW_ADDRESS}`);
  console.log(`   Simulated Caller: ${SELLER_ADDRESS}`);
  console.log(`   Target Tx ID    : ${TARGET_TX_ID}`);

  try {
    const callResult = await provider.call({
      to: ESCROW_ADDRESS,
      from: SELLER_ADDRESS,
      data: calldata,
    });
    console.log(`\n   ✓ eth_call SUCCEEDED!`);
    console.log(`   Return data: "${callResult}" (Expected 0x for void return function)`);
    console.log('\nContract state check:');
    const onchainState = await client.getOnchainTransactionState(TARGET_TX_ID);
    console.log(`   Current authoritative onchain state: ${onchainState} (Index: 1 PROPOSED)`);
    console.log('\nCONCLUSION: agreeTransaction simulation with corrected selector succeeded cleanly on Monad Testnet!');
  } catch (err) {
    console.error('\n❌ eth_call REVERTED!');
    console.error('Error message:', err.message);
    if (err.data) {
      console.error('Revert data:', err.data);
    }
    process.exit(1);
  }
}

main().catch(console.error);
